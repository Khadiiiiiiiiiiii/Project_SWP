    /**
     * Handles the HTTP <code>GET</code> method.
     *
     * @param request servlet request
     * @param response servlet response
     * @throws ServletException if a servlet-specific error occurs
     * @throws IOException if an I/O error occurs
     */
    @Override
    protected void doGet(HttpServletRequest request, HttpServletResponse response)
            throws ServletException, IOException {
        HttpSession session = request.getSession();
        User u = (User) session.getAttribute("user");
        OrderDAO od = new OrderDAO();
        List<HistoryOrder> list = new ArrayList<>();
        try {
            list = od.getHistoryOrder(u.getUserId());
        } catch (SQLException ex) {
            Logger.getLogger(HistoryOrder.class.getName()).log(Level.SEVERE, null, ex);
        }
        Map<Long, List<HistoryOrder>> groupedOrders = new HashMap<>();
        for (HistoryOrder ho : list) {
            groupedOrders.computeIfAbsent(Long.parseLong(String.valueOf(ho.getOrderId())), k -> new ArrayList<>()).add(ho);
        }
        session.setAttribute("groupedOrders", groupedOrders);
        request.getRequestDispatcher("HistoryOrder.jsp").forward(request, response);
    }

